-- Apply once to the Supabase PostgreSQL project used by this Flask app.
-- The Flask server connects privately with DATABASE_URL; never expose that URL in the browser.

CREATE TABLE IF NOT EXISTS product (
    product_id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name text NOT NULL,
    price numeric(12, 2) NOT NULL CHECK (price >= 0),
    description text NOT NULL DEFAULT ''
);

CREATE TABLE IF NOT EXISTS user_account (
    user_id uuid PRIMARY KEY DEFAULT gen_random_uuid(),
    username text NOT NULL UNIQUE,
    password_hash text NOT NULL
);

CREATE TABLE IF NOT EXISTS cart (
    user_id text NOT NULL,
    product_id text NOT NULL,
    quantity integer NOT NULL DEFAULT 1 CHECK (quantity BETWEEN 1 AND 10),
    added_at timestamptz NOT NULL DEFAULT now(),
    PRIMARY KEY (user_id, product_id)
);

CREATE TABLE IF NOT EXISTS wishlist (
    user_id text NOT NULL,
    product_id text NOT NULL,
    added_at timestamptz NOT NULL DEFAULT now(),
    PRIMARY KEY (user_id, product_id)
);

CREATE TABLE IF NOT EXISTS saved_carts (
    saved_cart_id uuid PRIMARY KEY DEFAULT gen_random_uuid(),
    user_id text NOT NULL,
    name text NOT NULL DEFAULT 'Saved cart',
    items jsonb NOT NULL DEFAULT '[]'::jsonb,
    created_at timestamptz NOT NULL DEFAULT now(),
    updated_at timestamptz NOT NULL DEFAULT now()
);

CREATE TABLE IF NOT EXISTS search_history (
    search_id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id text NOT NULL,
    query text NOT NULL,
    searched_at timestamptz NOT NULL DEFAULT now()
);

CREATE TABLE IF NOT EXISTS customer_ui_state (
    user_id text NOT NULL,
    state_key text NOT NULL,
    state_value jsonb NOT NULL,
    updated_at timestamptz NOT NULL DEFAULT now(),
    PRIMARY KEY (user_id, state_key)
);

CREATE INDEX IF NOT EXISTS cart_user_idx ON cart (user_id);
CREATE INDEX IF NOT EXISTS wishlist_user_idx ON wishlist (user_id);
CREATE INDEX IF NOT EXISTS saved_carts_user_idx ON saved_carts (user_id, updated_at DESC);
CREATE INDEX IF NOT EXISTS search_history_user_idx ON search_history (user_id, searched_at DESC);

-- Keep these tables inaccessible through Supabase's Data API unless explicit,
-- ownership-aware policies are added later. The trusted Flask server uses its
-- private PostgreSQL connection and always scopes customer queries by user_id.
ALTER TABLE cart ENABLE ROW LEVEL SECURITY;
ALTER TABLE wishlist ENABLE ROW LEVEL SECURITY;
ALTER TABLE saved_carts ENABLE ROW LEVEL SECURITY;
ALTER TABLE search_history ENABLE ROW LEVEL SECURITY;
ALTER TABLE customer_ui_state ENABLE ROW LEVEL SECURITY;
ALTER TABLE user_account ENABLE ROW LEVEL SECURITY;
ALTER TABLE product ENABLE ROW LEVEL SECURITY;
