-- Run in Supabase SQL Editor after schema.sql has created public.product.
-- Product descriptions, reviews, and highlights remain separate from app code.

CREATE TABLE IF NOT EXISTS product_details (
    detail varchar(15000) NOT NULL,
    prid bigint PRIMARY KEY REFERENCES product(product_id) ON DELETE CASCADE
);

CREATE TABLE IF NOT EXISTS reviews (
    review_id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    prid bigint NOT NULL REFERENCES product(product_id) ON DELETE CASCADE,
    user_id text NOT NULL,
    rating smallint NOT NULL CHECK (rating BETWEEN 1 AND 5),
    title varchar(200) NOT NULL DEFAULT '',
    review_text varchar(15000) NOT NULL,
    created_at timestamptz NOT NULL DEFAULT now()
);

CREATE TABLE IF NOT EXISTS top_highlights (
    highlight_id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    prid bigint NOT NULL REFERENCES product(product_id) ON DELETE CASCADE,
    highlight varchar(500) NOT NULL,
    display_order smallint NOT NULL DEFAULT 1 CHECK (display_order > 0),
    UNIQUE (prid, display_order)
);

CREATE INDEX IF NOT EXISTS reviews_prid_created_idx
    ON reviews (prid, created_at DESC);
CREATE INDEX IF NOT EXISTS top_highlights_prid_order_idx
    ON top_highlights (prid, display_order);

ALTER TABLE product_details ENABLE ROW LEVEL SECURITY;
ALTER TABLE reviews ENABLE ROW LEVEL SECURITY;
ALTER TABLE top_highlights ENABLE ROW LEVEL SECURITY;

-- These tables are read/written by the private Flask database connection.
REVOKE ALL ON TABLE product_details, reviews, top_highlights
    FROM anon, authenticated;
